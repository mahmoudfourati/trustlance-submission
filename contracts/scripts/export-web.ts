// Copies the escrow ABI and every Ignition deployment address into the web app,
// so the frontend never hand-copies contract data. Run after `hardhat build` / `ignition deploy`.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const contractsDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(contractsDir, "..", "web", "src", "contracts", "generated");
const artifactPath = join(contractsDir, "artifacts", "contracts", "TrustLanceEscrow.sol", "TrustLanceEscrow.json");
const deploymentsDir = join(contractsDir, "ignition", "deployments");
const futureId = "TrustLanceEscrowModule#TrustLanceEscrow";

const { abi } = JSON.parse(readFileSync(artifactPath, "utf8"));

const addresses: Record<number, string> = {};
if (existsSync(deploymentsDir)) {
  for (const entry of readdirSync(deploymentsDir)) {
    const match = /^chain-(\d+)$/.exec(entry);
    const file = join(deploymentsDir, entry, "deployed_addresses.json");
    if (!match || !existsSync(file)) continue;
    const deployed = JSON.parse(readFileSync(file, "utf8"));
    if (deployed[futureId]) addresses[Number(match[1])] = deployed[futureId];
  }
}

mkdirSync(outDir, { recursive: true });
const header = "// Generated by contracts/scripts/export-web.ts. Do not edit.\n";
writeFileSync(join(outDir, "escrowAbi.ts"), `${header}export const escrowAbi = ${JSON.stringify(abi, null, 2)} as const;\n`);
writeFileSync(
  join(outDir, "deployments.ts"),
  `${header}export const escrowAddresses: Record<number, string> = ${JSON.stringify(addresses, null, 2)};\n`,
);
console.log(`Exported ABI and ${Object.keys(addresses).length} deployment(s) to ${outDir}`);
